createPath :: (T.Render n b) => [(n, n)] -> T.TDiagram n b
createPath x =
  getPointsList x
    # D.fromVertices
    # D.strokePath
    # D.fillRule D.EvenOdd
    # D.lw (D.global 0.045)
    # D.lineJoin D.LineJoinBevel

getPathsList ::
  (T.Render n b) =>
  [[(n, n)]] -> T.TDiagram n b
getPathsList =
  mconcat
    . map createPath

getPointsList :: [(n, n)] -> [D.Point D.V2 n]
getPointsList = map D.p2
